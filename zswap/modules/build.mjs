#!/usr/bin/env node
/**
 * Cut zSwap's wallet code out of the deployed page into standalone ES modules.
 *
 * The page is the source. Each block below is copied out of dapp/page.html
 * byte for byte, located by the exact text it starts and ends with, so a
 * module can only say what the deployed page says. The few one-line helpers
 * the blocks lean on (U8, Er, Js, ...) are declared again at the top of each
 * module, and every one of those declarations must appear verbatim in the
 * page too, or the build stops.
 *
 *   walletconnect.js   WalletConnect v2: crypto (WCU), relay client (WCCLI),
 *                      QR encoder (QR8)
 *   wallets.js         EIP-6963 wallet discovery
 *
 * Usage: node zswap/modules/build.mjs [--check]
 *   --check  rebuild in memory and fail if a committed module differs
 */
import {createHash} from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DAPP = path.resolve(HERE, "..");
const manifest = JSON.parse(fs.readFileSync(path.join(DAPP, "manifest.json"), "utf8"));
const page = fs.readFileSync(path.join(DAPP, manifest.page), "utf8");
const sha256 = createHash("sha256").update(page).digest("hex");
if (sha256 !== manifest.sha256) {
  console.error(`page is ${sha256}, manifest pins ${manifest.sha256}`);
  process.exit(1);
}

const fail = (msg) => {
  console.error(msg);
  process.exit(1);
};

/** The text from `start` up to and including `end`, where `end` must be
 *  followed by `next`. Each anchor has to occur exactly once. */
function cut(start, end, next) {
  const once = (s) => {
    const i = page.indexOf(s);
    if (i < 0 || page.indexOf(s, i + 1) >= 0) fail(`anchor not unique in page: ${s.slice(0, 60)}`);
    return i;
  };
  const a = once(start);
  const b = page.indexOf(end + next, a);
  if (b < 0) fail(`no "${end}" before "${next.slice(0, 40)}" after ${start.slice(0, 40)}`);
  const text = page.slice(a, b + end.length);
  const line = page.slice(0, a).split("\n").length;
  return {text, line, lines: text.split("\n").length};
}

/** One-line helpers, declared exactly as the page declares them. */
const HELPERS = {
  Bi: "BigInt",
  St: "String",
  Nm: "Number",
  Dn: "()=>Date.now()",
  Er: "(...a)=>Error(...a)",
  Js: "JSON.stringify",
  Jp: "JSON.parse",
  Pa: "a=>Promise.all(a)",
  Mf: "Math.floor",
  Mn: "Math.min",
  U8: "(...a)=>new Uint8Array(...a)",
  Ni: "Number.isInteger",
  Oa: "Object.assign",
  Ok: "Object.keys",
  Np: "()=>{}",
  h16: "x=>x.toString(16)",
  Zz: "m=>new Promise(r=>setTimeout(r,m))",
  GB: '"eth_getBalance"',
  Sx: 'h=>h.startsWith("0x")?h.slice(2):h',
  hB: "h=>{const s=Sx(h);const o=U8(s.length/2);for(let i=0;i<o.length;i++)o[i]=parseInt(s.slice(i*2,i*2+2),16);return o}",
  cpHex: 'b=>{let s="";for(const x of b)s+=h16(x).padStart(2,"0");return s}',
  cpU8: "s=>new TextEncoder().encode(s)",
  nowS: "()=>Mf(Dn()/1e3)+tSk",
};
for (const [k, v] of Object.entries(HELPERS)) {
  if (!page.includes(`${k}=${v}`)) fail(`helper ${k} is not declared in the page as ${k}=${v}`);
}
const helpers = (names) => names.map((k) => `const ${k}=${HELPERS[k]};`).join("\n");

const WCU = cut("const WCU=(()=>{", "})();", "\nconst WCCLI=");
const WCCLI = cut("const WCCLI=(U,WSC)=>{", "};", "\nconst QR8=");
const QR8 = cut("const QR8=(()=>{", "})();", "\nconst wcNode=");
const W6963 = cut('addEventListener("eip6963:announceProvider",e=>{', "wkScan();", "\nlet WC_PID=");

const head = (what, blocks) =>
  `// GENERATED by zswap/modules/build.mjs from zswap/${manifest.page}\n` +
  `// page sha256 ${sha256}\n` +
  `// ${what}\n` +
  blocks.map(([name, b]) => `//   ${name}: page lines ${b.line}-${b.line + b.lines - 1}, verbatim`).join("\n") +
  `\n// Do not edit this file: change the page and rebuild.\n`;

const files = {
  "walletconnect.js":
    head("WalletConnect v2 client, as deployed in zSwap.", [["WCU", WCU], ["WCCLI", WCCLI], ["QR8", QR8]]) +
    `\n// Helpers the blocks use, declared exactly as in the page.\n` +
    helpers(["Bi", "St", "Nm", "Dn", "Er", "Js", "Jp", "Pa", "Mf", "Mn", "U8", "Ni", "Oa", "Ok", "Np", "h16", "Zz", "GB", "Sx", "hB", "cpHex", "cpU8"]) +
    `\nconst tSk=0;\n${helpers(["nowS"])}\n\n` +
    `// Crypto and encoding: ChaCha20-Poly1305, X25519 / HKDF via WebCrypto, did:key, relay JWT.\n` +
    `${WCU.text}\n\n` +
    `// QR code encoder for the pairing URI.\n` +
    `${QR8.text}\n\n` +
    `/** A relay client. In the page CHAINS and WC_RELAY are app globals; here they are options.\n` +
    ` *  Returns { pair(projectId, meta), resume(projectId, session), request(session, method, params),\n` +
    ` *            close(), end(session), on(listener) }. */\n` +
    `export function createClient({chains = [1, 8453, 4663], relay = "wss://relay.walletconnect.org", WebSocket: WS = globalThis.WebSocket} = {}) {\n` +
    `const CHAINS = Object.fromEntries(chains.map((id) => [id, true]));\n` +
    `const WC_RELAY = [relay];\n` +
    `${WCCLI.text}\n` +
    `return WCCLI(WCU, (u) => new WS(u));\n}\n\n` +
    `export {WCU, QR8};\n`,
  "wallets.js":
    head("EIP-6963 wallet discovery, as deployed in zSwap.", [["eip6963", W6963]]) +
    `\nconst W6963=[];\n${W6963.text}\n\n` +
    `/** Wallets that have announced themselves: [{ info: {uuid, name, icon, rdns}, provider }]. */\n` +
    `export const wallets = () => W6963.slice();\n` +
    `/** Ask installed wallets to announce again. */\n` +
    `export const rescan = wkScan;\n`,
};

const check = process.argv.includes("--check");
let stale = 0;
for (const [name, text] of Object.entries(files)) {
  const file = path.join(HERE, name);
  if (check) {
    const now = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    if (now !== text) {
      console.error(`  STALE ${name}: rebuild with node zswap/modules/build.mjs`);
      stale++;
    } else console.log(`  ok    ${name} matches the page`);
  } else {
    fs.writeFileSync(file, text);
    console.log(`  wrote ${name} (${text.length} B)`);
  }
}
process.exit(stale ? 1 : 0);
